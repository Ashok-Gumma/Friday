import React, { createContext, useContext, useState, useEffect } from "react";

const ThemeContext = createContext();

export const ThemeProvider = ({ children }) => {
  const [theme, setTheme] = useState(() => {
    const saved = localStorage.getItem("friday_theme");
    if (saved === "light" || saved === "dark") return saved;
    // Default to dark for sleek Notion dark aesthetic, or check system preference
    return window.matchMedia?.("(prefers-color-scheme: dark)").matches ? "dark" : "dark";
  });

  useEffect(() => {
    localStorage.setItem("friday_theme", theme);
    document.documentElement.setAttribute("data-theme", theme);
    // Also add class for utility classes if needed
    if (theme === "dark") {
      document.documentElement.classList.add("dark");
      document.documentElement.classList.remove("light");
    } else {
      document.documentElement.classList.add("light");
      document.documentElement.classList.remove("dark");
    }
  }, [theme]);

  const toggleTheme = () => {
    setTheme(prev => (prev === "dark" ? "light" : "dark"));
  };

  return (
    <ThemeContext.Provider value={{ theme, setTheme, toggleTheme, isDark: theme === "dark" }}>
      {children}
    </ThemeContext.Provider>
  );
};

export const useTheme = () => {
  const context = useContext(ThemeContext);
  if (!context) {
    throw new Error("useTheme must be used within a ThemeProvider");
  }
  return context;
};
